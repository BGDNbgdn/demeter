// Vegetables and fruit.
const V = 'vegetable', FR = 'fruit';
// veg(base, displayName, retentionPercent, aliases, cookedSuffix)
// USDA raw entry = `${base}, raw`; cooked = `${base}, cooked, boiled, drained, without salt`
const veg = (base, name, ret, aliases = [], opts = {}) => {
  const out = [[`^${base}, raw`, `${name}, raw`, V, 'raw', { ret, aliases, ...(opts.serv ? { serv: opts.serv } : {}) }]];
  if (!opts.noCooked) out.push([`^${base}, ${opts.cooked || 'cooked, boiled, drained(, without salt)?$'}`, `${name}, ${opts.cookedLabel || 'boiled'}`, V, 'cooked', { aliases }]);
  return out;
};
const fruit = (match, name, aliases = [], serv) => [match, name, FR, 'raw', { aliases, ...(serv ? { serv } : {}) }];

